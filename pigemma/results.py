def _split_experiments(values: Sequence[str] | None) -> list[str] | None:
    if not values:
        return None
    out: list[str] = []
    for v in values:
        for part in v.split(","):
            if part.strip():
                out.append(normalize_experiment(part.strip()))
    return out or None


def _parse_set(item: str) -> tuple[str, Any]:
    if "=" not in item:
        raise ValueError(f"--set expects key=value, got {item!r}")
    key, val = item.split("=", 1)
    key = key.strip()
    if not key:
        raise ValueError(f"--set expects key=value, got {item!r}")
    try:
        parsed: Any = json.loads(val)
    except json.JSONDecodeError:
        parsed = val  # bare string
    return key, parsed


def _set_dotted(d: dict[str, Any], dotted: str, value: Any) -> None:
    parts = dotted.split(".")
    cur = d
    for p in parts[:-1]:
        nxt = cur.get(p)
        if not isinstance(nxt, dict):
            nxt = {}
            cur[p] = nxt
        cur = nxt
    cur[parts[-1]] = value


def _cmd_summarize(args: argparse.Namespace) -> int:
    missing = [t for t in args.inputs if not _expand(t, True)[1]]
    for t in missing:
        sys.stderr.write(f"pigemma.results: no such file, directory or glob match: {t}\n")
    present = [t for t in args.inputs if t not in missing]
    if not present:
        return paths.EXIT_MISSING
    md = summarize(present, args.md, experiments=_split_experiments(args.experiment), title=args.title)
    if args.md is None:
        sys.stdout.write(md)
    else:
        n = md.count("\n")
        print(f"wrote {args.md} ({n} lines)")
    return paths.EXIT_MISSING if missing else paths.EXIT_OK


def _cmd_validate(args: argparse.Namespace) -> int:
    report: list[dict[str, Any]] = []
    any_err = False
    any_missing = False
    for t in args.files:
        files, existed = _expand(t, True)
        if not existed:
            any_missing = True
            report.append({"file": t, "ok": False, "errors": ["no such file, directory or glob match"],
                           "warnings": []})
            continue
        is_dir_input = Path(t).is_dir()
        for f in files:
            try:
                obj = read_json_file(f)
            except (OSError, UnicodeDecodeError, json.JSONDecodeError) as e:
                any_err = True
                report.append({"file": str(f), "ok": False, "errors": [f"unparsable: {e}"], "warnings": []})
                continue
            if is_dir_input and not is_envelope(obj):
                continue  # directories may hold sim.json, meta.json, raw tool output ...
            errs, warns = check_result(obj)
            if args.strict:
                errs = errs + [f"(strict) {w}" for w in warns]
                warns = []
            any_err = any_err or bool(errs)
            report.append({"file": str(f), "ok": not errs, "errors": errs, "warnings": warns})
    if args.json:
        print(json.dumps({"ok": not any_err and not any_missing, "files": report}, indent=1, ensure_ascii=False))
    else:
        for r in report:
            print(("OK   " if r["ok"] else "FAIL ") + r["file"])
            for e in r["errors"]:
                print(f"  error: {e}")
            for w in r["warnings"]:
                print(f"  warning: {w}")
        n_ok = sum(1 for r in report if r["ok"])
        print(f"{n_ok}/{len(report)} valid")
    if any_err:
        return paths.EXIT_ERROR
    if any_missing:
        return paths.EXIT_MISSING
    return paths.EXIT_OK


def _cmd_write(args: argparse.Namespace) -> int:
    fields: dict[str, Any] = {}
    if args.fields:
        try:
            if args.fields == "-":
                raw = sys.stdin.read()
                if raw.startswith("﻿"):
                    raw = raw[1:]
                obj = json.loads(raw)
            else:
                obj = read_json_file(args.fields)
        except FileNotFoundError:
            sys.stderr.write(f"pigemma.results: no such file: {args.fields}\n")
            return paths.EXIT_MISSING
        except (OSError, json.JSONDecodeError) as e:
            sys.stderr.write(f"pigemma.results: cannot read --fields {args.fields}: {e}\n")
            return paths.EXIT_ERROR
        if not isinstance(obj, dict):
            sys.stderr.write("pigemma.results: --fields must contain a JSON object\n")
            return paths.EXIT_ERROR
        fields.update(obj)
    for item in args.set or []:
        key, val = _parse_set(item)
        _set_dotted(fields, key, val)
    if args.pinned_llama:
        fields.setdefault("llama_build", paths.LLAMA_BUILD)
        fields.setdefault("llama_commit", paths.LLAMA_COMMIT)
    try:
        p = write_result(args.out, **fields)
    except ResultSchemaError as e:
        sys.stderr.write(f"pigemma.results: {e}\n")
        return paths.EXIT_ERROR
    print(p)
    return paths.EXIT_OK


def _build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(
        prog="python -m pigemma.results",
        description="Results envelope (measured / projected / assumed): summarise, validate, write.",
        epilog="Exit codes: 0 ok, 1 schema errors or unparsable files, 2 usage, 3 input not found.",
    )
    ap.add_argument("--log-level", default="INFO", help="logging level on stderr (default INFO)")
    sub = ap.add_subparsers(dest="cmd", metavar="<command>")

    s = sub.add_parser("summarize", help="render results JSON files as markdown (MEASURED / PROJECTED / ASSUMED)")
    s.add_argument("inputs", nargs="+", help="directories (scanned recursively for *.json), files or globs")
    s.add_argument("--md", default=None, help="output markdown file (default: print to stdout)")
    s.add_argument("--experiment", action="append", default=None,
                   help="only these experiments (E0..E8, adhoc; comma list or repeat)")
    s.add_argument("--title", default="Results summary", help="document title")

    v = sub.add_parser("validate", help="schema-check results files; exit 1 on any error")
    v.add_argument("files", nargs="+", help="files, globs or directories (dirs: envelope-like *.json only)")
    v.add_argument("--strict", action="store_true", help="treat warnings (unknown keys, ...) as errors")
    v.add_argument("--json", action="store_true", help="machine-readable report on stdout")

    w = sub.add_parser("write", help="write one envelope from JSON fields (for shell scripts)")
    w.add_argument("--out", required=True, help="output .json file, or an existing directory (auto name)")
    w.add_argument("--fields", default=None, help="JSON object file with the fields ('-' = stdin)")
    w.add_argument("--set", action="append", default=None, metavar="KEY=JSON",
                   help="set a field (dotted keys allowed, e.g. tg.tok_s=2.4; non-JSON values are strings)")
    w.add_argument("--pinned-llama", action="store_true",
                   help=f"default llama_build/llama_commit to the pinned {paths.LLAMA_BUILD}/{paths.LLAMA_COMMIT}")
    return ap


def main(argv: list[str] | None = None) -> int:
    """CLI entry point; returns the process exit code."""
    for stream in (sys.stdout, sys.stderr):
        with contextlib.suppress(Exception):
            stream.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[attr-defined]
    ap = _build_parser()
    args = ap.parse_args(sys.argv[1:] if argv is None else argv)
    if not logging.getLogger().handlers:
        logging.basicConfig(
            level=getattr(logging, str(args.log_level).upper(), logging.INFO),
            format="%(asctime)s %(levelname)s %(name)s: %(message)s",
            stream=sys.stderr,
        )
    if args.cmd is None:
        ap.print_help()
        return paths.EXIT_USAGE
    try:
        if args.cmd == "summarize":
            return _cmd_summarize(args)
        if args.cmd == "validate":
            return _cmd_validate(args)
        if args.cmd == "write":
            return _cmd_write(args)
    except ValueError as e:
        sys.stderr.write(f"pigemma.results: {e}\n")
        return paths.EXIT_USAGE
    except Exception as e:  # noqa: BLE001 - CLI boundary
        sys.stderr.write(f"pigemma.results: error: {type(e).__name__}: {e}\n")
        return paths.EXIT_ERROR
    ap.print_help()
    return paths.EXIT_USAGE


if __name__ == "__main__":
    sys.exit(main())
