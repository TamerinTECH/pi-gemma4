def _canonical_order(doc: Mapping[str, Any]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for k in REQUIRED_KEYS + OPTIONAL_KEYS:
        if k in doc and k != "extra":
            out[k] = doc[k]
    for k in doc:
        if k not in out and k != "extra":
            out[k] = doc[k]
    if "extra" in doc:
        out["extra"] = doc["extra"]
    return out


def build_result(**fields: Any) -> dict[str, Any]:
    """Normalise + validate an envelope; returns the canonical dict. Raises ResultSchemaError.

    Auto-fills run_id, created_at and host when absent or None (see the module docstring for the
    full list of normalisations). Keys starting with '_' are dropped.
    """
    doc: dict[str, Any] = {k: v for k, v in fields.items() if not str(k).startswith("_")}
    notes_added: list[str] = []

    # generated-by-definition fields
    if doc.get("run_id") is None:
        doc["run_id"] = new_run_id()
    elif isinstance(doc["run_id"], uuid.UUID):
        doc["run_id"] = str(doc["run_id"])
    if doc.get("created_at") is None:
        doc["created_at"] = utc_now_iso()
    if doc.get("host") is None:
        doc["host"] = paths.host_fingerprint()

    # lenient normalisation of caller-supplied fields
    if isinstance(doc.get("experiment"), str):
        with contextlib.suppress(ValueError):
            doc["experiment"] = normalize_experiment(doc["experiment"])
    if isinstance(doc.get("kind"), str):
        doc["kind"] = doc["kind"].strip().lower()
    m = doc.get("model")
    if isinstance(m, (str, os.PathLike)):
        doc["model"] = model_block(m)
    elif isinstance(m, Mapping):
        mm = dict(m)
        miss = [k for k in MODEL_KEYS if k not in mm]
        if miss:
            log.warning("model block lacks %s; stored as null", ", ".join(miss))
            for k in miss:
                mm[k] = None
        doc["model"] = {**{k: mm[k] for k in MODEL_KEYS}, **{k: v for k, v in mm.items() if k not in MODEL_KEYS}}
    fl = doc.get("flags")
    if isinstance(fl, str):
        doc["flags"] = shlex.split(fl, posix=True)
    elif isinstance(fl, tuple):
        doc["flags"] = list(fl)
    if isinstance(doc.get("flags"), list):
        doc["flags"] = [os.fspath(x) if isinstance(x, os.PathLike) else
                        (str(x) if _is_num(x) else x) for x in doc["flags"]]
    for k in ("threads", "n_ctx", "llama_build", "draft_n", "draft_n_accepted", "qa_total"):
        if k in doc:
            doc[k] = _coerce_int(doc[k])
    if isinstance(doc.get("notes"), str):
        doc["notes"] = [doc["notes"]]
    elif isinstance(doc.get("notes"), tuple):
        doc["notes"] = list(doc["notes"])
    if isinstance(doc.get("inputs"), (str, os.PathLike)):
        doc["inputs"] = [doc["inputs"]]
    if isinstance(doc.get("inputs"), (list, tuple)):
        doc["inputs"] = [paths.repo_relative(x) if isinstance(x, os.PathLike) else x for x in doc["inputs"]]
    if "assumptions" in doc and isinstance(doc["assumptions"], Mapping):
        doc["assumptions"] = normalize_assumptions(doc["assumptions"])
    for k in ("pp", "tg"):
        if isinstance(doc.get(k), Mapping):
            blk = dict(doc[k])
            for sub in ("sd", "n"):
                blk.setdefault(sub, None)
            if "n" in blk:
                blk["n"] = _coerce_int(blk["n"])
            doc[k] = {**{s: blk.get(s) for s in RATE_KEYS if s in blk},
                      **{s: v for s, v in blk.items() if s not in RATE_KEYS}}
    s = doc.get("output_sample")
    if isinstance(s, str) and len(s) > OUTPUT_SAMPLE_MAX:
        notes_added.append(f"output_sample truncated from {len(s)} to {OUTPUT_SAMPLE_MAX} chars")
        doc["output_sample"] = s[:OUTPUT_SAMPLE_MAX]

    # unknown top-level keys -> extra
    unknown = [k for k in doc if k not in KNOWN_KEYS]
    if unknown:
        extra = doc.get("extra")
        if extra is None:
            extra = {}
        if isinstance(extra, Mapping):
            extra = dict(extra)
            for k in unknown:
                dest = k if k not in extra else f"toplevel_{k}"
                extra[dest] = doc.pop(k)
            doc["extra"] = extra
            log.warning("unknown top-level keys moved under 'extra': %s", ", ".join(unknown))

    try:
        doc = _sanitize(doc, "", notes_added)
    except TypeError as e:
        raise ResultSchemaError([str(e)]) from e
    if notes_added:
        notes = doc.get("notes")
        if notes is None:
            notes = []
        if isinstance(notes, list):
            doc["notes"] = list(notes) + notes_added

    doc = _canonical_order(doc)
    errors, warns = check_result(doc)
    for w in warns:
        log.warning("%s", w)
    if errors:
        raise ResultSchemaError(errors, _missing_from(errors))
    return doc


def new_result(experiment: str, kind: str, **fields: Any) -> dict[str, Any]:
    """build_result with llama_build / llama_commit defaulting to the pinned build (paths).

    Pass the build the tool actually reported (llama-bench JSON build_number / build_commit)
    whenever there is one; the default is for results produced by the pinned binaries.
    """
    fields.setdefault("llama_build", paths.LLAMA_BUILD)
    fields.setdefault("llama_commit", paths.LLAMA_COMMIT)
    return build_result(experiment=experiment, kind=kind, **fields)


def _fname_part(x: Any) -> str:
    s = re.sub(r"[^A-Za-z0-9.\-]+", "-", str(x)).strip("-.")
    return s or "na"


def result_filename(doc: Mapping[str, Any]) -> str:
    """'<experiment>_<model>_<variant>_<threads>_<YYYYmmddTHHMMSSZ>_<run_id[:8]>.json'.

    The trailing run-id fragment keeps names unique when several results (e.g. pp and tg rows of
    one llama-bench call) are written within the same second.
    """
    model = doc.get("model")
    mid = None
    if isinstance(model, Mapping):
        mid = model.get("id") or (Path(str(model.get("file"))).stem if model.get("file") else None)
    try:
        ts = parse_created_at(str(doc.get("created_at"))).strftime("%Y%m%dT%H%M%SZ")
    except ValueError:
        ts = _dt.datetime.now(_dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    threads = doc.get("threads")
    parts = [
        _fname_part(doc.get("experiment") or "adhoc"),
        _fname_part(mid or "nomodel"),
        _fname_part(doc.get("variant") or "na"),
        _fname_part(threads if threads is not None else "na"),
        ts,
        _fname_part(str(doc.get("run_id") or new_run_id())[:8]),
    ]
    return "_".join(parts) + ".json"


def _atomic_write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp{os.getpid()}")
    try:
        with open(tmp, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
            f.flush()
            with contextlib.suppress(OSError):
                os.fsync(f.fileno())
        os.replace(tmp, path)
    finally:
        with contextlib.suppress(OSError):
            if tmp.exists():
                tmp.unlink()


def dumps_result(doc: Mapping[str, Any]) -> str:
    """Serialise an envelope exactly as write_result stores it (UTF-8 JSON, indent 1, LF)."""
    return json.dumps(doc, indent=1, ensure_ascii=False, allow_nan=False) + "\n"


def write_result(path: str | os.PathLike[str], /, **fields: Any) -> Path:
    """Build, validate and atomically write one results envelope; returns the written path.

    ``path`` is the JSON file to write, or a directory - an existing one, a string ending in a path
    separator, or a not-yet-existing path without a suffix - in which case the file name comes
    from :func:`result_filename`. Parent directories are created. Raises ResultSchemaError (a ValueError) listing missing keys and every other error;
    nothing is written then.
    """
    doc = build_result(**fields)
    p = Path(os.fspath(path))
    raw = os.fspath(path)
    if p.is_dir() or raw.endswith(("/", "\\")) or (not p.exists() and p.suffix == ""):
        p = p / result_filename(doc)
    if p.suffix.lower() != ".json":
        log.warning("%s does not end in .json; load_results/summarize only pick up *.json", p)
    _atomic_write_text(p, dumps_result(doc))
    log.info("wrote %s (%s %s %s)", p, doc["experiment"], doc["kind"], doc["variant"])
    return p


