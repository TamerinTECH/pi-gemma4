class _Missing:
    """Sentinel: metric absent from the result."""


_MISSING = _Missing()


def _get(doc: Mapping[str, Any], dotted: str) -> Any:
    """Value at a dotted path; _MISSING when the top-level key is absent, None when a sub-key is."""
    parts = dotted.split(".")
    if parts[0] not in doc:
        return _MISSING
    cur: Any = doc[parts[0]]
    for p in parts[1:]:
        if not isinstance(cur, Mapping):
            return None
        cur = cur.get(p)
    return cur


def _fmt_num(v: Any) -> str:
    if isinstance(v, bool):
        return "yes" if v else "no"
    if _is_int(v):
        return f"{v:,}"
    if _is_num(v):
        a = abs(v)
        if a >= 1000:
            return f"{v:,.0f}"
        if a >= 100:
            return f"{v:.1f}"
        if a >= 1 or a == 0:
            return f"{v:.2f}"
        return f"{v:.3g}"
    return str(v)


def _fmt_rate(v: Any) -> str:
    if not isinstance(v, Mapping):
        return _fmt_num(v)
    t = v.get("tok_s")
    if t is None:
        return NA
    s = f"{t:.2f}" if _is_num(t) else str(t)
    sd = v.get("sd")
    if _is_num(sd):
        s += f" ± {sd:.2f}"
    n = v.get("n")
    if _is_int(n):
        s += f" (n={n})"
    return s


def _fmt_mb_per_token(v: Any) -> str:
    return f"{v / 1e6:,.1f}" if _is_num(v) else str(v)


def _fmt_pct(v: Any) -> str:
    if isinstance(v, bool):
        return "yes" if v else "no"
    return f"{100.0 * v:.1f}%" if _is_num(v) else str(v)


def _fmt_buffers(v: Any) -> str:
    if not isinstance(v, Mapping):
        return str(v)
    label = {"CPU_REPACK_mib": "REPACK", "CPU_Mapped_mib": "Mapped", "CPU_mib": "CPU"}
    parts = []
    keys = [k for k in BUFFER_KEYS if k in v] + [k for k in v if k not in BUFFER_KEYS]
    for k in keys:
        x = v[k]
        name = label.get(k, k[:-4] if k.endswith("_mib") else k)
        parts.append(f"{name} {_fmt_num(x) if x is not None else NA}")
    return " / ".join(parts) + " MiB" if parts else NA


def _fmt_qa(doc: Mapping[str, Any]) -> Any:
    if "qa_score" not in doc and "qa_total" not in doc:
        return _MISSING
    sc, tot = doc.get("qa_score"), doc.get("qa_total")
    if sc is None:
        return None
    return f"{_fmt_num(sc)}/{_fmt_num(tot)}" if tot is not None else _fmt_num(sc)


