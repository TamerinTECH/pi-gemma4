def _code(text: str, limit: int | None = None) -> str:
    s = text if limit is None or len(text) <= limit else text[: limit - 1] + "…"
    if "`" in s:
        return s
    return f"`{s}`" if s else ""


def _table(headers: Sequence[str], rows: Sequence[Sequence[Any]]) -> list[str]:
    out = ["| " + " | ".join(_cell(h) for h in headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(_cell(c) for c in r) + " |")
    return out


def _host_label(h: Any) -> str:
    if not isinstance(h, Mapping):
        return NA
    name = str(h.get("hostname") or NA)
    tags = []
    if h.get("emulated"):
        tags.append("emulated")
    if h.get("in_container"):
        tags.append("container")
    return name + (f" [{', '.join(tags)}]" if tags else "")


def _model_key(doc: Mapping[str, Any]) -> str:
    m = doc.get("model")
    if isinstance(m, Mapping):
        if m.get("id"):
            return str(m["id"])
        if m.get("file"):
            return Path(str(m["file"])).name
    return "(no model)"


def _model_heading(key: str, docs: Sequence[Mapping[str, Any]]) -> list[str]:
    models = [d.get("model") for d in docs if isinstance(d.get("model"), Mapping)]
    if not models:
        return [f"#### Model: {key}", ""]
    m = models[0]
    bits = []
    if m.get("quant"):
        bits.append(str(m["quant"]))
    if _is_int(m.get("bytes")):
        bits.append(f"{m['bytes'] / 1e9:.2f} GB")
    if m.get("sha_prefix"):
        bits.append(f"sha256[16 MiB] {str(m['sha_prefix'])[:12]}")
    line = f"#### Model `{key}`"
    if m.get("file"):
        line += f" - {_code(str(m['file']))}"
    if bits:
        line += f" ({', '.join(bits)})"
    out = [line, ""]
    shas = {(mm.get("sha_prefix"), mm.get("bytes")) for mm in models}
    if len(shas) > 1:
        out += [f"_Caution: rows below come from {len(shas)} different files with this model id "
                "(sha256 prefix / size differ)._", ""]
    return out


def _row_sort_key(d: Mapping[str, Any]) -> tuple[str, int, str, str]:
    t = d.get("threads")
    return (str(d.get("variant", "")), t if _is_int(t) else -1, str(d.get("created_at", "")),
            str(d.get("_path", "")))


def _metrics_for(exp: str, docs: Sequence[Mapping[str, Any]]) -> list[str]:
    base = list(EXPERIMENT_METRICS.get(exp, DEFAULT_METRICS))
    present = [k for k in METRIC_ORDER if k not in base
               and any(METRICS[k][1](d) is not _MISSING for d in docs)]
    return base + present


def _render_table(exp: str, kind: str, docs: Sequence[Mapping[str, Any]], start: int) -> tuple[list[str], int]:
    """One model table (+ notes, + assumptions/inputs for projected/assumed). Returns (lines, next index)."""
    metrics = _metrics_for(exp, docs)
    headers = ["#", "variant", "threads", "n_ctx", "flags"] + [METRICS[k][0] for k in metrics] \
        + ["host", "date (UTC)", "file"]
    rows = []
    refs: list[tuple[str, Mapping[str, Any]]] = []
    i = start
    for d in docs:
        i += 1
        ref = f"{ROW_PREFIX[kind]}{i}"
        refs.append((ref, d))
        flags = d.get("flags")
        flag_txt = " ".join(flags) if isinstance(flags, list) else ""
        cells: list[Any] = [
            ref,
            d.get("variant", NA),
            _fmt_num(d["threads"]) if _is_int(d.get("threads")) else NA,
            _fmt_num(d["n_ctx"]) if _is_int(d.get("n_ctx")) else NA,
            _code(flag_txt, 60) if flag_txt else "(none)",
        ]
        for k in metrics:
            _, getter, fmt = METRICS[k]
            raw = getter(d)
            if raw is _MISSING:
                cells.append(NOT_RUN)
            elif raw is None:
                cells.append(NA)
            else:
                cells.append(fmt(raw))
        created = str(d.get("created_at", ""))
        cells += [
            _host_label(d.get("host")),
            created[:16].replace("T", " ") if created else NA,
            _code(Path(str(d.get("_path", ""))).name) if d.get("_path") else "(in memory)",
        ]
        rows.append(cells)
    lines = _table(headers, rows) + [""]

    note_lines = []
    for ref, d in refs:
        for n in d.get("notes") or []:
            note_lines.append(f"- {ref}: {_cell(n)}")
    if note_lines:
        lines += ["Notes:", ""] + note_lines + [""]

    if kind in ("projected", "assumed"):
        used: dict[tuple[str, str, str, str], list[str]] = {}
        for ref, d in refs:
            a = d.get("assumptions")
            if not isinstance(a, Mapping):
                continue
            for name, e in a.items():
                if not isinstance(e, Mapping):
                    continue
                val = e.get("value")
                vtxt = _fmt_num(val) if (_is_num(val) or isinstance(val, bool)) else \
                    json.dumps(val, ensure_ascii=False) if not isinstance(val, str) else val
                key = (str(name), vtxt, str(e.get("unit") if e.get("unit") is not None else ""),
                       str(e.get("source", "")))
                used.setdefault(key, []).append(ref)
        lines += ["**Assumptions used**", ""]
        if used:
            arows = [[k[0], k[1], k[2] or "-", k[3], ", ".join(v)] for k, v in sorted(used.items())]
            lines += _table(["name", "value", "unit", "source", "used by"], arows) + [""]
        else:
            lines += ["_None recorded (invalid for this kind; see Skipped results)._", ""]
        inp = []
        for ref, d in refs:
            ins = d.get("inputs")
            if isinstance(ins, list) and ins:
                inp.append(f"- {ref}: " + ", ".join(_code(str(x)) for x in ins))
        if inp:
            lines += ["Inputs:", ""] + inp + [""]
    return lines, i


def render_markdown(
    results: Sequence[Mapping[str, Any]],
    *,
    experiments: Sequence[str] | None = None,
    title: str = "Results summary",
    sources: Sequence[str] | None = None,
    skipped: Sequence[tuple[str, str]] | None = None,
) -> str:
    """Render loaded envelopes as markdown (see the module docstring for the layout).

    ``results`` should be valid envelopes (summarize() filters invalid ones into ``skipped``:
    (path, reason) pairs listed at the end). ``experiments`` restricts the output.
    """
    exp_filter = {normalize_experiment(e) for e in experiments} if experiments else None
    docs = [d for d in results if exp_filter is None or d.get("experiment") in exp_filter]
    by_exp: dict[str, list[Mapping[str, Any]]] = {}
    for d in docs:
        by_exp.setdefault(str(d.get("experiment")), []).append(d)
    exps = sorted(by_exp, key=_exp_sort_key)
    if exp_filter:
        exps = sorted(set(exps) | exp_filter, key=_exp_sort_key)

    counts = {k: sum(1 for d in docs if d.get("kind") == k) for k in KINDS}
    out: list[str] = [f"# {title}", ""]
    out.append(f"Generated {utc_now_iso()} by `python -m pigemma.results summarize`"
               + (f" from {', '.join(_code(s) for s in sources)}" if sources else "") + ".")
    out.append(f"{len(docs)} result file(s): {counts['measured']} measured, {counts['projected']} "
               f"projected, {counts['assumed']} assumed"
               + (f"; {len(skipped)} skipped (see the end)." if skipped else "."))
    out += ["",
            "Legend: **MEASURED** = observed on the named host; **PROJECTED** = computed from measured "
            "inputs plus the listed assumptions; **ASSUMED** = taken as given, not measured here. "
            f"'{NOT_RUN}' = the result has no such metric; '{NA}' = the metric was recorded as null "
            "(not applicable / not available). Hosts tagged [emulated] ran under qemu: functional "
            "proof only, their speed is not a Pi measurement.",
            ""]
    if exps:
        out += ["## Overview", ""]
        orows = []
        for e in exps:
            ds = by_exp.get(e, [])
            models = sorted({_model_key(d) for d in ds})
            orows.append([e, EXPERIMENT_TITLES.get(e, ""),
                          *(str(sum(1 for d in ds if d.get("kind") == k)) for k in KINDS),
                          ", ".join(models) if models else "-"])
        out += _table(["experiment", "title", "measured", "projected", "assumed", "models"], orows) + [""]
    else:
        out += ["_No results found._", ""]

    for e in exps:
        ds = by_exp.get(e, [])
        out += [f"## {e}: {EXPERIMENT_TITLES.get(e, 'other')}", ""]
        for kind in KINDS:
            out += [f"### {SECTION_TITLES[kind]}", "", f"_{SECTION_BLURBS[kind]}_", ""]
            kd = [d for d in ds if d.get("kind") == kind]
            if not kd:
                out += [f"_No {kind} results for {e}._", ""]
                continue
            by_model: dict[str, list[Mapping[str, Any]]] = {}
            for d in kd:
                by_model.setdefault(_model_key(d), []).append(d)
            idx = 0
            for mk in sorted(by_model, key=lambda k: (k == "(no model)", k)):
                group = sorted(by_model[mk], key=_row_sort_key)
                out += _model_heading(mk, group)
                lines, idx = _render_table(e, kind, group, idx)
                out += lines
    if skipped:
        out += ["## Skipped results", "",
                "_These files look like results envelopes but fail validation; they are not in any "
                "table above. Fix them or run `python -m pigemma.results validate <file>`._", ""]
        out += _table(["file", "reason"], [[_code(p), r] for p, r in skipped]) + [""]
    return "\n".join(out).rstrip("\n") + "\n"


def summarize(
    inputs: str | os.PathLike[str] | Sequence[str | os.PathLike[str]],
    md_out: str | os.PathLike[str] | None = None,
    *,
    experiments: Sequence[str] | None = None,
    title: str = "Results summary",
) -> str:
    """Load envelopes from ``inputs``, render markdown, optionally write it to ``md_out``.

    Envelopes failing validation are excluded from the tables and listed under "Skipped results".
    Returns the markdown text.
    """
    targets = [inputs] if isinstance(inputs, (str, os.PathLike)) else list(inputs)
    loaded = load_results(targets)
    good: list[dict[str, Any]] = []
    skipped: list[tuple[str, str]] = []
    for d in loaded:
        errs, _ = check_result({k: v for k, v in d.items() if k != "_path"})
        if errs:
            log.warning("excluded from summary (invalid): %s: %s", d.get("_path"), "; ".join(errs[:3]))
            skipped.append((paths.repo_relative(d["_path"]), "; ".join(errs[:3])))
        else:
            good.append(d)
    md = render_markdown(good, experiments=experiments, title=title,
                         sources=[paths.repo_relative(os.fspath(t)) if not _GLOB_CHARS.search(os.fspath(t))
                                  else os.fspath(t) for t in targets],
                         skipped=skipped)
    if md_out is not None:
        _atomic_write_text(Path(os.fspath(md_out)), md)
        log.info("wrote %s", md_out)
    return md


