def _check_rate_block(name: str, v: Any, errors: list[str]) -> None:
    if not isinstance(v, Mapping):
        errors.append(f"{name} must be an object {{tok_s, sd, n}}, got {type(v).__name__}")
        return
    if "tok_s" not in v:
        errors.append(f"{name}.tok_s is missing")
    for k in ("tok_s", "sd"):
        x = v.get(k)
        if x is not None and not _is_num(x):
            errors.append(f"{name}.{k} must be a finite number or null, got {x!r}")
        elif x is not None and x < 0:
            errors.append(f"{name}.{k} must be >= 0, got {x!r}")
    n = v.get("n")
    if n is not None and not (_is_int(n) and n >= 0):
        errors.append(f"{name}.n must be an integer >= 0 or null, got {n!r}")


def _check_num_or_null(name: str, v: Any, errors: list[str], *, lo: float | None = None,
                       hi: float | None = None, integer: bool = False) -> None:
    if v is None:
        return
    if integer and not _is_int(v):
        errors.append(f"{name} must be an integer or null, got {v!r}")
        return
    if not _is_num(v):
        errors.append(f"{name} must be a finite number or null, got {v!r}")
        return
    if lo is not None and v < lo:
        errors.append(f"{name} must be >= {lo:g}, got {v!r}")
    if hi is not None and v > hi:
        errors.append(f"{name} must be <= {hi:g}, got {v!r}")


def check_result(doc: Any) -> tuple[list[str], list[str]]:
    """Schema check of one envelope dict. Returns (errors, warnings); never raises.

    Errors start with 'missing required key: <k>' for each missing key, followed by type / value
    errors. Warnings cover unknown top-level keys, an incomplete host block and a measured result
    that carries assumptions.
    """
    errors: list[str] = []
    warns: list[str] = []
    if not isinstance(doc, Mapping):
        return [f"envelope must be a JSON object, got {type(doc).__name__}"], warns

    kind = doc.get("kind")
    for k in REQUIRED_KEYS:
        if k not in doc:
            errors.append(f"missing required key: {k}")
    if isinstance(kind, str) and kind in KINDS and kind != "measured":
        for k in REQUIRED_UNLESS_MEASURED:
            if k not in doc:
                errors.append(f"missing required key: {k} (required when kind={kind!r})")

    # --- required keys: values
    if "run_id" in doc:
        v = doc["run_id"]
        if not (isinstance(v, str) and _UUID_RE.match(v.lower())):
            errors.append(f"run_id must be a uuid4 string, got {v!r}")
    if "experiment" in doc:
        v = doc["experiment"]
        if v not in EXPERIMENTS:
            errors.append(f"experiment must be one of {', '.join(EXPERIMENTS)}, got {v!r}")
    if "created_at" in doc:
        try:
            parse_created_at(doc["created_at"])
        except (ValueError, TypeError) as e:
            errors.append(str(e))
    if "kind" in doc and kind not in KINDS:
        errors.append(f"kind must be one of {', '.join(KINDS)}, got {kind!r}")
    if "host" in doc:
        h = doc["host"]
        if not isinstance(h, Mapping):
            errors.append(f"host must be an object (paths.host_fingerprint()), got {type(h).__name__}")
        else:
            hn = h.get("hostname")
            if not (isinstance(hn, str) and hn.strip()):
                errors.append("host.hostname must be a non-empty string")
            miss = [k for k in HOST_KEYS if k not in h]
            if miss:
                warns.append("host block lacks " + ", ".join(miss) + " (use paths.host_fingerprint())")
    if "llama_build" in doc:
        _check_num_or_null("llama_build", doc["llama_build"], errors, lo=0, integer=True)
    if "llama_commit" in doc:
        v = doc["llama_commit"]
        if v is not None and not (isinstance(v, str) and v.strip()):
            errors.append(f"llama_commit must be a non-empty string or null, got {v!r}")
    if "model" in doc:
        m = doc["model"]
        if m is not None:
            if not isinstance(m, Mapping):
                errors.append(f"model must be an object {{{', '.join(MODEL_KEYS)}}} or null, got {type(m).__name__}")
            else:
                miss = [k for k in MODEL_KEYS if k not in m]
                if miss:
                    errors.append("model block lacks " + ", ".join(miss))
                for k in ("id", "file", "quant", "sha_prefix"):
                    x = m.get(k)
                    if x is not None and not isinstance(x, str):
                        errors.append(f"model.{k} must be a string or null, got {x!r}")
                b = m.get("bytes")
                if b is not None and not (_is_int(b) and b >= 0):
                    errors.append(f"model.bytes must be an integer >= 0 or null, got {b!r}")
                if not m.get("id") and not m.get("file"):
                    errors.append("model needs at least one of id / file (use model=None if no model is involved)")
    if "variant" in doc:
        v = doc["variant"]
        if not (isinstance(v, str) and v.strip()):
            errors.append(f"variant must be a non-empty string, got {v!r}")
    if "flags" in doc:
        v = doc["flags"]
        if not (isinstance(v, list) and all(isinstance(x, str) for x in v)):
            errors.append(f"flags must be a list of strings, got {v!r}")
    if "threads" in doc:
        _check_num_or_null("threads", doc["threads"], errors, lo=1, integer=True)
    if "n_ctx" in doc:
        _check_num_or_null("n_ctx", doc["n_ctx"], errors, lo=0, integer=True)

    # --- assumptions / inputs
    if "assumptions" in doc:
        a = doc["assumptions"]
        if not isinstance(a, Mapping):
            errors.append(f"assumptions must be an object {{name: {{value, unit, source}}}}, got {type(a).__name__}")
        else:
            if kind in ("projected", "assumed") and not a:
                errors.append(f"assumptions must be non-empty when kind={kind!r}")
            for name, e in a.items():
                if not (isinstance(name, str) and name.strip()):
                    errors.append(f"assumption name must be a non-empty string, got {name!r}")
                if not isinstance(e, Mapping):
                    errors.append(f"assumptions.{name} must be an object {{value, unit, source}}, got {e!r}")
                    continue
                miss = [k for k in ASSUMPTION_KEYS if k not in e]
                if miss:
                    errors.append(f"assumptions.{name} lacks " + ", ".join(miss))
                src = e.get("source")
                if "source" in e and not (isinstance(src, str) and src.strip()):
                    errors.append(f"assumptions.{name}.source must be a non-empty string")
                u = e.get("unit")
                if u is not None and not isinstance(u, str):
                    errors.append(f"assumptions.{name}.unit must be a string or null, got {u!r}")
            if kind == "measured" and a:
                warns.append("measured result carries assumptions; numbers derived from them belong in "
                             "a separate kind='projected' result (or under extra)")
    if "inputs" in doc:
        v = doc["inputs"]
        if not (isinstance(v, list) and all(isinstance(x, str) and x.strip() for x in v)):
            errors.append(f"inputs must be a list of non-empty path strings, got {v!r}")
        elif kind == "projected" and not v:
            errors.append("inputs must be non-empty when kind='projected' (with no measured input "
                          "use kind='assumed')")

    # --- optional metrics
    for name in ("pp", "tg"):
        if name in doc and doc[name] is not None:
            _check_rate_block(name, doc[name], errors)
    for name in ("load_s", "rss_peak_mb", "private_peak_mb", "mapped_mb", "read_bytes_per_token",
                 "majflt_per_token", "io_rbytes_per_token", "ppl"):
        if name in doc:
            _check_num_or_null(name, doc[name], errors, lo=0)
    if "buffer_split" in doc and doc["buffer_split"] is not None:
        bs = doc["buffer_split"]
        if not isinstance(bs, Mapping):
            errors.append(f"buffer_split must be an object {{{', '.join(BUFFER_KEYS)}}}, got {bs!r}")
        else:
            for k, x in bs.items():
                _check_num_or_null(f"buffer_split.{k}", x, errors, lo=0)
    if "accept_rate" in doc:
        _check_num_or_null("accept_rate", doc["accept_rate"], errors, lo=0, hi=1)
    for name in ("draft_n", "draft_n_accepted", "qa_total"):
        if name in doc:
            _check_num_or_null(name, doc[name], errors, lo=0, integer=True)
    if "qa_score" in doc:
        _check_num_or_null("qa_score", doc["qa_score"], errors, lo=0)
    if _is_num(doc.get("qa_score")) and _is_int(doc.get("qa_total")) and doc["qa_score"] > doc["qa_total"]:
        errors.append(f"qa_score {doc['qa_score']} exceeds qa_total {doc['qa_total']}")
    if _is_int(doc.get("draft_n")) and _is_int(doc.get("draft_n_accepted")) \
            and doc["draft_n_accepted"] > doc["draft_n"]:
        errors.append(f"draft_n_accepted {doc['draft_n_accepted']} exceeds draft_n {doc['draft_n']}")
    if "spec_type_effective" in doc:
        v = doc["spec_type_effective"]
        if v is not None and not isinstance(v, str):
            errors.append(f"spec_type_effective must be a string or null, got {v!r}")
    for name in ("spec_active", "coherent"):
        if name in doc:
            v = doc[name]
            if v is not None and not isinstance(v, bool):
                errors.append(f"{name} must be true/false/null, got {v!r}")
    if "identical_to_plain" in doc:
        v = doc["identical_to_plain"]
        if v is not None and not isinstance(v, bool):
            _check_num_or_null("identical_to_plain", v, errors, lo=0, hi=1)
    if "kld" in doc and doc["kld"] is not None:
        k = doc["kld"]
        if not isinstance(k, Mapping):
            errors.append(f"kld must be an object {{{', '.join(KLD_KEYS)}}}, got {k!r}")
        else:
            for sub in ("mean", "max", "p999", "ppl_q", "ppl_base"):
                if sub in k:
                    _check_num_or_null(f"kld.{sub}", k[sub], errors, lo=0)
            if "same_top_p" in k:
                _check_num_or_null("kld.same_top_p", k["same_top_p"], errors, lo=0, hi=1)
    if "output_sample" in doc:
        v = doc["output_sample"]
        if v is not None and not isinstance(v, str):
            errors.append(f"output_sample must be a string or null, got {type(v).__name__}")
        elif isinstance(v, str) and len(v) > OUTPUT_SAMPLE_MAX:
            errors.append(f"output_sample is {len(v)} chars (max {OUTPUT_SAMPLE_MAX})")
    if "notes" in doc:
        v = doc["notes"]
        if not (isinstance(v, list) and all(isinstance(x, str) for x in v)):
            errors.append(f"notes must be a list of strings, got {v!r}")
    if "extra" in doc:
        v = doc["extra"]
        if not isinstance(v, Mapping):
            errors.append(f"extra must be an object, got {type(v).__name__}")

    unknown = sorted(k for k in doc if isinstance(k, str) and k not in KNOWN_KEYS and not k.startswith("_"))
    if unknown:
        warns.append("unknown top-level keys (belong under 'extra'): " + ", ".join(unknown))
    return errors, warns


def validate_result(doc: Any, *, strict: bool = False) -> list[str]:
    """Errors of one envelope (empty list = valid). Warnings are logged, or returned as errors
    when ``strict`` is true."""
    errors, warns = check_result(doc)
    if strict:
        return errors + [f"(strict) {w}" for w in warns]
    for w in warns:
        log.warning("%s", w)
    return errors


def _missing_from(errors: Iterable[str]) -> list[str]:
    out = []
    for e in errors:
        if e.startswith("missing required key: "):
            out.append(e[len("missing required key: "):].split(" ")[0])
    return out


