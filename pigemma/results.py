def _expand(target: str | os.PathLike[str], recursive: bool) -> tuple[list[Path], bool]:
    """Files for one input (dir / file / glob). Returns (files, existed)."""
    raw = os.fspath(target)
    p = Path(raw)
    if p.is_dir():
        it = p.rglob("*.json") if recursive else p.glob("*.json")
        return sorted(x for x in it if x.is_file() and not x.name.startswith(".")), True
    if p.is_file():
        return [p], True
    if _GLOB_CHARS.search(raw):
        hits = sorted(Path(x) for x in _glob.glob(raw, recursive=True))
        files: list[Path] = []
        for h in hits:
            if h.is_dir():
                it = h.rglob("*.json") if recursive else h.glob("*.json")
                files.extend(sorted(x for x in it if x.is_file()))
            elif h.is_file():
                files.append(h)
        return files, bool(hits)
    return [], False


def read_json_file(path: str | os.PathLike[str]) -> Any:
    """json.load with UTF-8 (a BOM, as PowerShell 5.1 writes it, is tolerated)."""
    with open(path, "r", encoding="utf-8-sig") as f:
        return json.load(f)


def is_envelope(obj: Any) -> bool:
    """True for a JSON object that claims to be a results envelope (has experiment and kind)."""
    return isinstance(obj, Mapping) and "experiment" in obj and "kind" in obj


def _exp_sort_key(exp: Any) -> tuple[int, str]:
    if exp in EXPERIMENTS:
        return (EXPERIMENTS.index(exp), "")
    return (len(EXPERIMENTS), str(exp))


def load_results(
    dir_or_glob: str | os.PathLike[str] | Iterable[str | os.PathLike[str]],
    *,
    recursive: bool = True,
    validate: bool = False,
) -> list[dict[str, Any]]:
    """Load every results envelope from directories, files and/or glob patterns.

    * Directories are scanned for ``*.json`` (recursively by default; dot-files skipped).
    * Unparsable files are skipped with a logged WARNING; valid JSON that is not an envelope
      (no ``experiment``/``kind``: llama-bench raw output, sim.json, meta.json, ...) is skipped with
      a DEBUG line and counted in one INFO line.
    * With ``validate=True`` envelopes that fail :func:`check_result` are skipped with a WARNING.
    * Each returned dict gets ``_path`` (str) = the file it came from. Duplicated files are loaded
      once; a run_id seen twice keeps the first file (WARNING).

    Sorted by (experiment order E0..E8, adhoc, other), created_at, path.
    """
    if isinstance(dir_or_glob, (str, os.PathLike)):
        targets: list[str | os.PathLike[str]] = [dir_or_glob]
    else:
        targets = list(dir_or_glob)
    seen_files: set[str] = set()
    seen_ids: dict[str, str] = {}
    out: list[dict[str, Any]] = []
    n_other = 0
    for t in targets:
        files, existed = _expand(t, recursive)
        if not existed:
            log.warning("no such file, directory or glob match: %s", os.fspath(t))
            continue
        for f in files:
            key = os.path.normcase(str(f.resolve()))
            if key in seen_files:
                continue
            seen_files.add(key)
            try:
                obj = read_json_file(f)
            except (OSError, UnicodeDecodeError, json.JSONDecodeError) as e:
                log.warning("skipping unparsable results file %s: %s", f, e)
                continue
            if not is_envelope(obj):
                n_other += 1
                log.debug("not a results envelope, skipped: %s", f)
                continue
            if validate:
                errs, _ = check_result(obj)
                if errs:
                    log.warning("skipping invalid results file %s: %s", f, "; ".join(errs[:3]))
                    continue
            rid = obj.get("run_id")
            if isinstance(rid, str) and rid in seen_ids:
                log.warning("duplicate run_id %s in %s (already loaded from %s); skipped", rid, f, seen_ids[rid])
                continue
            if isinstance(rid, str):
                seen_ids[rid] = str(f)
            d = dict(obj)
            d["_path"] = str(f)
            out.append(d)
    if n_other:
        log.info("skipped %d JSON file(s) that are not results envelopes", n_other)
    out.sort(key=lambda d: (_exp_sort_key(d.get("experiment")), str(d.get("created_at", "")), d["_path"]))
    return out


