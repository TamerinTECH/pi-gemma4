"""pigemma.results - the one results-JSON envelope (desktop, Docker, emulated Pi, Pi) + summariser.

Every number this project reports lives in one JSON file per run with the same envelope
(docs/design/manifest.json -> data_formats "results JSON envelope"). The envelope says, in a
mandatory ``kind`` field, whether its numbers were MEASURED on the named host, PROJECTED from
measured inputs plus listed assumptions, or merely ASSUMED (literature / catalog values). A
projected or assumed result must carry the assumptions it used ({name: {value, unit, source}})
so measured, projected and assumed numbers are never mixed silently; the summariser renders
them in separate, clearly labelled sections.

Python API (stdlib only; imports nothing but pigemma.paths, so it runs on a bare Pi Python 3.13)::

    write_result(path, **fields) -> Path        build + validate + atomic write (ValueError on errors)
    build_result(**fields) -> dict              the same without writing (fills defaults, normalises)
    new_result(experiment, kind, **fields)      build_result with the pinned llama build/commit filled
    check_result(doc) -> (errors, warnings)     pure schema check of an envelope dict
    validate_result(doc, strict=False) -> errors
    load_results(dir_or_glob, ...) -> list[dict] (skips unparsable / non-envelope files with a log line)
    render_markdown(results, ...) -> str        the summary document
    summarize(inputs, md_out=None, ...) -> str  load + render (+ write)
    result_filename(doc) -> str                 '<experiment>_<model>_<variant>_<threads>_<ts>_<run8>.json'
    assumption(value, unit, source) / normalize_assumptions(d) / model_block(id_or_path)

CLI (``python -m pigemma.results <cmd> --help``)::

    summarize <dir|file|glob>... [--md OUT.md] [--experiment E0[,E1]]... [--title T]
    validate  <file|dir|glob>... [--strict] [--json]
    write     --out <file|dir> [--fields F.json|-] [--set key=JSON]... [--pinned-llama]

Exit codes (pigemma.paths): 0 ok; 1 schema errors / unparsable files (validate, write);
2 usage; 3 an input path does not exist / matched nothing.

Envelope rules (decisions taken here where the manifest left room; all are documented in the
interface notes of this module):

* Required keys: run_id (uuid4 string), experiment ('E0'..'E8' or 'adhoc'), created_at (ISO-8601
  UTC, 'Z' or '+00:00'), kind ('measured'|'projected'|'assumed'), host (dict, at least hostname),
  llama_build (int|None), llama_commit (str|None), model ({id, file, quant, bytes, sha_prefix} or
  None when no model is involved), variant (non-empty str), flags (list[str]), threads (int >= 1 |
  None), n_ctx (int >= 0 | None). kind != 'measured' additionally requires a NON-EMPTY
  ``assumptions`` dict and an ``inputs`` list; for kind='projected' ``inputs`` must be non-empty
  too (a projection always derives from something; with nothing measured in, use kind='assumed').
* ``write_result``/``build_result`` AUTO-FILL only what is generated by definition: run_id (fresh
  uuid4), created_at (now, UTC) and host (paths.host_fingerprint()). llama_build/llama_commit are
  NOT auto-filled (a measured result must state the build that produced it); ``new_result`` and
  ``write --pinned-llama`` fill the pinned a7b94df / 11398 when the caller has nothing better.
* Lenient normalisation before validation (so a 10-minute model run is never lost to a typo):
  experiment 'E0-desktop-baseline...' -> 'E0'; kind is lower-cased; ``model`` given as an id or a
  path is resolved with paths.model_identity(); a model dict missing some of the five keys gets
  them as None (warning); flags given as a string are shlex-split; notes given as a string become
  a list; Path objects become repo-relative strings; numpy scalars/arrays become Python values;
  non-finite floats become null (with a note); output_sample is truncated to 2000 chars (with a
  note); assumption entries without a unit get one from the name suffix (_bytes -> 'B', _mbps ->
  'MB/s', ...) or None; UNKNOWN TOP-LEVEL KEYS ARE MOVED UNDER ``extra`` with a warning (the
  manifest allows unknown keys only under extra). Validation of files on disk (``validate``) does
  not normalise: unknown top-level keys are warnings there (errors with --strict).
* Keys starting with '_' are private: ``load_results`` attaches ``_path`` (the file it came from);
  build/write drop such keys and the validator ignores them.
* Markdown: per experiment three sections MEASURED / PROJECTED / ASSUMED (always all three
  headers, an explicit "no ... results" line when empty), each split by model, each projected or
  assumed table followed by an "Assumptions used" sub-table (name | value | unit | source | used
  by) and the inputs list. A metric that is absent from a result renders as 'not run'; a metric
  that is present but null (ran, value unavailable / not applicable) renders as 'n/a'. Results
  that fail validation are excluded from the tables and listed in a "Skipped results" section.
* Emulated hosts (host.emulated) and containers (host.in_container) are tagged in the host column:
  emulated speed numbers are functional proofs, not Pi measurements.
"""

