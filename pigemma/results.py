class ResultSchemaError(ValueError):
    """Raised by build_result / write_result when an envelope is invalid.

    ``errors`` lists every problem; ``missing`` the missing required keys (also named first in the
    message, as the manifest asks).
    """

    def __init__(self, errors: Sequence[str], missing: Sequence[str] = ()) -> None:
        self.errors = list(errors)
        self.missing = list(missing)
        head = "invalid results envelope"
        if self.missing:
            head += ": missing required keys: " + ", ".join(self.missing)
        rest = [e for e in self.errors if not e.startswith("missing required key")]
        super().__init__(head + (("; " + "; ".join(rest)) if rest else ""))


