def new_run_id() -> str:
    """A fresh uuid4 string for ``run_id``."""
    return str(uuid.uuid4())


def utc_now_iso() -> str:
    """Current time as ISO-8601 UTC with a 'Z' suffix (second resolution)."""
    return _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def parse_created_at(value: str) -> _dt.datetime:
    """Parse an envelope ``created_at`` string (UTC only). Raises ValueError otherwise."""
    if not isinstance(value, str) or not _ISO_RE.match(value):
        raise ValueError(f"created_at must be ISO-8601 UTC like 2026-10-05T10:15:00Z, got {value!r}")
    s = value[:-1] + "+00:00" if value.endswith("Z") else value
    if re.search(r"[+-]0000$", s):
        s = s[:-5] + "+00:00"
    # fromisoformat accepts at most 6 fractional digits on older Pythons
    s = re.sub(r"(\.\d{6})\d+", r"\1", s)
    dt = _dt.datetime.fromisoformat(s)
    if dt.utcoffset() != _dt.timedelta(0):
        raise ValueError(f"created_at must be UTC, got {value!r}")
    return dt


def normalize_experiment(value: Any) -> str:
    """'E0', 'e0', 'E0-desktop-baseline-and-repack-gate' -> 'E0'; 'adhoc' (any case) -> 'adhoc'.

    Raises ValueError for anything else (E9+, empty, non-strings).
    """
    if isinstance(value, str):
        if value.strip().lower() == "adhoc":
            return "adhoc"
        m = _EXP_RE.match(value)
        if m:
            return f"E{m.group(1)}"
    raise ValueError(f"experiment must be one of {', '.join(EXPERIMENTS)} (or 'E<n>-<name>'), got {value!r}")


def infer_unit(name: str) -> str | None:
    """Best-effort unit for an assumption name (DEFAULT_UNITS, then suffix rules), else None."""
    if name in DEFAULT_UNITS:
        return DEFAULT_UNITS[name]
    low = name.lower()
    for suffix, unit in _UNIT_SUFFIXES:
        if low.endswith(suffix):
            return unit
    return None


def assumption(value: Any, unit: str | None, source: str) -> dict[str, Any]:
    """One entry of the ``assumptions`` dict: {'value', 'unit', 'source'}."""
    return {"value": value, "unit": unit, "source": source}


def normalize_assumptions(
    assumptions: Mapping[str, Any] | None, units: Mapping[str, str] | None = None
) -> dict[str, Any]:
    """Normalise assumption entries to {name: {value, unit, source}} (other keys are kept).

    Accepts {name: {value, source[, unit]}} (sim.json / catalog style) or {name: (value, unit,
    source)} tuples. A missing unit is taken from ``units``, then :func:`infer_unit`, else None.
    Entries that cannot be normalised are passed through unchanged (validation reports them).
    """
    if assumptions is None:
        return {}
    if not isinstance(assumptions, Mapping):
        return assumptions  # type: ignore[return-value]  # validator reports the type error
    out: dict[str, Any] = {}
    for name, entry in assumptions.items():
        key = str(name)
        if isinstance(entry, (tuple, list)) and len(entry) == 3:
            out[key] = assumption(entry[0], entry[1], entry[2])
            continue
        if isinstance(entry, Mapping):
            e = dict(entry)
            if "unit" not in e:
                e["unit"] = (units or {}).get(key) or infer_unit(key)
            # canonical key order: value, unit, source, then anything else
            ordered = {k: e[k] for k in ASSUMPTION_KEYS if k in e}
            ordered.update({k: v for k, v in e.items() if k not in ordered})
            out[key] = ordered
            continue
        out[key] = entry
    return out


def model_block(id_or_path: str | os.PathLike[str], with_sha: bool = True) -> dict[str, Any]:
    """The envelope ``model`` block for a registry id or a GGUF path (paths.model_identity)."""
    return paths.model_identity(id_or_path, with_sha=with_sha)


def _is_num(x: Any) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)


def _is_int(x: Any) -> bool:
    return isinstance(x, int) and not isinstance(x, bool)


def _coerce_int(x: Any) -> Any:
    """'6' -> 6, 6.0 -> 6; anything else unchanged (the validator reports it)."""
    if isinstance(x, str) and re.fullmatch(r"\s*[+-]?\d+\s*", x):
        return int(x)
    if isinstance(x, float) and not isinstance(x, bool) and math.isfinite(x) and x.is_integer():
        return int(x)
    return x


def _sanitize(obj: Any, where: str, notes: list[str]) -> Any:
    """Make ``obj`` strictly JSON-serialisable without importing numpy.

    numpy scalars/arrays (anything with .item()/.tolist()) -> Python values; Path -> repo-relative
    string; tuple/set -> list; datetime -> ISO string; non-finite floats -> None (+ note).
    """
    if obj is None or isinstance(obj, (bool, str)):
        return obj
    if isinstance(obj, int):
        return int(obj)
    if isinstance(obj, float):
        if math.isfinite(obj):
            return float(obj)
        notes.append(f"non-finite value at {where or '<root>'} stored as null")
        return None
    if isinstance(obj, os.PathLike):
        return paths.repo_relative(obj)
    if isinstance(obj, _dt.datetime):
        if obj.tzinfo is None:
            obj = obj.replace(tzinfo=_dt.timezone.utc)
        return obj.astimezone(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    if isinstance(obj, uuid.UUID):
        return str(obj)
    if isinstance(obj, Mapping):
        return {str(k): _sanitize(v, f"{where}.{k}" if where else str(k), notes) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_sanitize(v, f"{where}[{i}]", notes) for i, v in enumerate(obj)]
    if isinstance(obj, (set, frozenset)):
        items = list(obj)
        with contextlib.suppress(TypeError):
            items = sorted(items)
        return [_sanitize(v, f"{where}[{i}]", notes) for i, v in enumerate(items)]
    # numpy (and friends) without importing numpy
    tolist = getattr(obj, "tolist", None)
    if callable(tolist) and getattr(obj, "ndim", 0):
        return _sanitize(tolist(), where, notes)
    item = getattr(obj, "item", None)
    if callable(item):
        with contextlib.suppress(Exception):
            return _sanitize(item(), where, notes)
    if callable(tolist):
        with contextlib.suppress(Exception):
            return _sanitize(tolist(), where, notes)
    raise TypeError(f"value at {where or '<root>'} is not JSON-serialisable: {type(obj).__name__}")


