__all__ = [
    "WORKLOADS_DIR", "SETS", "LANGS", "CATEGORIES", "CONTEXT_REUSE", "MAX_TOKENS_MIN",
    "MAX_TOKENS_MAX", "HELDOUT_GEN_BUDGET", "load_set", "load_all", "validate_conversation",
    "validate_all", "user_turns", "generation_budget", "request_messages", "render_gemma4",
    "shingles", "count_tokens", "expected_reuse_note", "external_corpus_texts", "main",
]

WORKLOADS_DIR: Path = paths.DATA_DIR / "workloads"
SETS = ("calibration", "tuning", "heldout")
LANGS = ("en", "he", "de", "mixed")
CATEGORIES = ("chat", "instruction_following", "code", "extraction", "summarization",
              "topic_switch", "follow_up", "translation")
CONTEXT_REUSE = ("none", "follow_up_same_conversation")
KEYS = ("id", "set", "lang", "category", "turns", "max_tokens", "context_reuse", "notes")
MAX_TOKENS_MIN = 48
MAX_TOKENS_MAX = 96
HELDOUT_GEN_BUDGET = 1500       # max generated tokens per method-repeat over the held-out set
SET_SIZE = {"calibration": (20, 28), "tuning": (6, 10), "heldout": (16, 20)}
SHINGLE_N = 8                   # words; a shared 8-word run between two sets = shared text

# Gemma 4 chat template tokens (tokenizer.chat_template of the Gemma 4 GGUFs, read 2026-10-05)
TURN_OPEN = "<|turn>"
TURN_CLOSE = "<turn|>"
EMPTY_THOUGHT = "<|channel>thought\n<channel|>"
BOS_TEXT = "<bos>"


class WorkloadError(ValueError):
    """A workload file is missing or malformed."""


# --------------------------------------------------------------------------------------------
# Loading and validation
# --------------------------------------------------------------------------------------------
def _set_path(name_or_path: str | os.PathLike[str], base: Path | None = None) -> Path:
    s = os.fspath(name_or_path)
    if s in SETS:
        return (base or WORKLOADS_DIR) / f"{s}.jsonl"
    return Path(s)


def load_set(name_or_path: str | os.PathLike[str], base: Path | None = None) -> list[dict[str, Any]]:
    """Conversations of one JSONL file (blank lines ignored; no validation beyond JSON)."""
    p = _set_path(name_or_path, base)
    if not p.is_file():
        raise WorkloadError(f"workload file not found: {p}")
    out: list[dict[str, Any]] = []
    with open(p, encoding="utf-8") as f:
        for ln, line in enumerate(f, 1):
            if not line.strip():
                continue
            try:
                obj = json.loads(line)
            except ValueError as e:
                raise WorkloadError(f"{p}:{ln}: invalid JSON: {e}") from e
            if not isinstance(obj, dict):
                raise WorkloadError(f"{p}:{ln}: not a JSON object")
            out.append(obj)
    return out


def load_all(base: str | os.PathLike[str] | None = None) -> dict[str, list[dict[str, Any]]]:
    d = Path(base) if base is not None else WORKLOADS_DIR
    return {s: load_set(s, d) for s in SETS}


def user_turns(conv: Mapping[str, Any]) -> list[str]:
    return [str(t.get("content", "")) for t in conv.get("turns") or [] if t.get("role") == "user"]


def generation_budget(conv: Mapping[str, Any]) -> int:
    """Upper bound of generated tokens of a conversation: max_tokens per user turn."""
    return int(conv.get("max_tokens") or 0) * len(user_turns(conv))


def validate_conversation(conv: Mapping[str, Any], expected_set: str | None = None) -> list[str]:
    """Schema errors of one conversation ([] when valid)."""
    cid = conv.get("id", "?")
    errs: list[str] = []
    keys = set(conv)
    missing = [k for k in KEYS if k not in keys]
    extra = sorted(keys - set(KEYS))
    if missing:
        errs.append(f"{cid}: missing keys {missing}")
    if extra:
        errs.append(f"{cid}: unknown keys {extra}")
    if not isinstance(conv.get("id"), str) or not re.fullmatch(r"[a-z]{2,3}-[a-z0-9-]+", str(cid)):
        errs.append(f"{cid}: id must look like 'ho-07' (lowercase prefix + '-' + suffix)")
    if conv.get("set") not in SETS:
        errs.append(f"{cid}: set {conv.get('set')!r} not in {SETS}")
    elif expected_set and conv.get("set") != expected_set:
        errs.append(f"{cid}: set {conv.get('set')!r} in the {expected_set} file")
    if conv.get("lang") not in LANGS:
        errs.append(f"{cid}: lang {conv.get('lang')!r} not in {LANGS}")
    if conv.get("category") not in CATEGORIES:
        errs.append(f"{cid}: category {conv.get('category')!r} not in {CATEGORIES}")
    mt = conv.get("max_tokens")
    if not isinstance(mt, int) or isinstance(mt, bool) or not MAX_TOKENS_MIN <= mt <= MAX_TOKENS_MAX:
        errs.append(f"{cid}: max_tokens {mt!r} outside {MAX_TOKENS_MIN}..{MAX_TOKENS_MAX}")
    if not isinstance(conv.get("notes"), str):
        errs.append(f"{cid}: notes must be a string")
    turns = conv.get("turns")
    if not isinstance(turns, list) or not turns:
        errs.append(f"{cid}: turns must be a non-empty list")
        return errs
    for i, t in enumerate(turns):
        if not isinstance(t, Mapping) or set(t) != {"role", "content"}:
            errs.append(f"{cid}: turn {i} must be exactly {{role, content}}")
            continue
        if t["role"] not in ("system", "user"):
            errs.append(f"{cid}: turn {i} role {t['role']!r} (only system/user; replies are generated)")
        if t["role"] == "system" and i != 0:
            errs.append(f"{cid}: a system message is only allowed as the first turn")
        if not isinstance(t["content"], str) or not t["content"].strip():
            errs.append(f"{cid}: turn {i} has empty content")
        elif t["content"] != t["content"].strip():
            errs.append(f"{cid}: turn {i} content has leading/trailing whitespace "
                        "(the template trims it; keep the stored text identical to what is sent)")
    n_user = len(user_turns(conv))
    if n_user == 0:
        errs.append(f"{cid}: no user turn")
    reuse = conv.get("context_reuse")
    if reuse not in CONTEXT_REUSE:
        errs.append(f"{cid}: context_reuse {reuse!r} not in {CONTEXT_REUSE}")
    elif (reuse == "none") != (n_user == 1):
        errs.append(f"{cid}: context_reuse {reuse!r} but {n_user} user turn(s) "
                    "(none <=> exactly one user turn)")
    if n_user > 1 and conv.get("category") not in ("topic_switch", "follow_up"):
        errs.append(f"{cid}: multi-turn conversations must be category topic_switch or follow_up")
    if n_user == 1 and conv.get("category") in ("topic_switch", "follow_up"):
        errs.append(f"{cid}: category {conv.get('category')} needs >= 2 user turns")
    return errs


_WS = re.compile(r"\s+")


def _norm(text: str) -> str:
    s = unicodedata.normalize("NFKC", str(text)).casefold()
    return _WS.sub(" ", s).strip()


def shingles(text: str, n: int = SHINGLE_N) -> set[str]:
    """Set of n-word runs of the normalised text (whole text when it has < n words)."""
    w = _norm(text).split(" ")
    if not w or w == [""]:
        return set()
    if len(w) < n:
        return {" ".join(w)} if len(w) >= 4 else set()
    return {" ".join(w[i:i + n]) for i in range(len(w) - n + 1)}


def _conv_texts(conv: Mapping[str, Any]) -> list[str]:
    return [str(t.get("content", "")) for t in conv.get("turns") or [] if isinstance(t, Mapping)]


def external_corpus_texts() -> dict[str, str]:
    """Texts the held-out and tuning sets must not share: the older routing-trace corpus
    (data/calibration/*) and the older prompt sets (data/prompts/qa_set, qa_hard, gen_prompts)."""
    out: dict[str, str] = {}
    if paths.CALIBRATION_DIR.is_dir():
        for p in sorted(paths.CALIBRATION_DIR.iterdir()):
            if p.is_file() and p.suffix in (".txt", ".cpp") and p.name != "all.txt":
                out[f"data/calibration/{p.name}"] = p.read_text(encoding="utf-8", errors="replace")
    for name in ("qa_set.json", "qa_hard.json", "gen_prompts.json"):
        p = paths.PROMPTS_DIR / name
        if p.is_file():
            try:
                items = json.loads(p.read_text(encoding="utf-8-sig"))
            except ValueError:
                continue
            for it in items if isinstance(items, list) else []:
                if isinstance(it, Mapping) and it.get("prompt"):
                    out[f"data/prompts/{name}#{it.get('id')}"] = str(it["prompt"])
    return out


def _overlaps(a: Mapping[str, set[str]], b: Mapping[str, set[str]]) -> list[tuple[str, str, str]]:
    index: dict[str, str] = {}
    for k, sh in b.items():
        for s in sh:
            index.setdefault(s, k)
    hits: list[tuple[str, str, str]] = []
    for k, sh in a.items():
        for s in sorted(sh):
            if s in index:
                hits.append((k, index[s], s))
                break
    return hits


def validate_all(base: str | os.PathLike[str] | None = None, *,
                 check_external: bool = True) -> dict[str, Any]:
    """Validate the three files: schema, unique ids, set sizes, held-out generation budget,
    pairwise disjointness (no identical turn, no shared 8-word run) and - for tuning and
    held-out - no shared text with the older trace corpus / prompt sets."""
    d = Path(base) if base is not None else WORKLOADS_DIR
    errors: list[str] = []
    sets: dict[str, list[dict[str, Any]]] = {}
    for s in SETS:
        try:
            sets[s] = load_set(s, d)
        except WorkloadError as e:
            errors.append(str(e))
            sets[s] = []
    seen: dict[str, str] = {}
    for s, convs in sets.items():
        for c in convs:
            errors.extend(validate_conversation(c, s))
            cid = str(c.get("id"))
            if cid in seen:
                errors.append(f"{cid}: duplicate id (also in {seen[cid]})")
            seen[cid] = s
        lo, hi = SET_SIZE[s]
        if convs and not lo <= len(convs) <= hi:
            errors.append(f"{s}: {len(convs)} conversations, expected {lo}..{hi}")
    ho_budget = sum(generation_budget(c) for c in sets.get("heldout", []))
    if ho_budget > HELDOUT_GEN_BUDGET:
        errors.append(f"heldout: generation budget {ho_budget} > {HELDOUT_GEN_BUDGET} tokens")
    # disjointness
    exact: dict[str, tuple[str, str]] = {}
    sh_by_set: dict[str, dict[str, set[str]]] = {}
    for s, convs in sets.items():
        sh_by_set[s] = {}
        for c in convs:
            cid = str(c.get("id"))
            allsh: set[str] = set()
            for t in _conv_texts(c):
                key = _norm(t)
                if key in exact and exact[key][0] != s:
                    errors.append(f"{cid}: a turn is identical to one of {exact[key][1]} ({exact[key][0]})")
                exact.setdefault(key, (s, cid))
                allsh |= shingles(t)
            sh_by_set[s][cid] = allsh
    for i, s1 in enumerate(SETS):
        for s2 in SETS[i + 1:]:
            for k1, k2, sh in _overlaps(sh_by_set[s1], sh_by_set[s2]):
                errors.append(f"{k1} ({s1}) shares text with {k2} ({s2}): {sh!r}")
    if check_external:
        ext = {k: shingles(v) for k, v in external_corpus_texts().items()}
        for s in ("tuning", "heldout"):
            for k1, k2, sh in _overlaps(sh_by_set[s], ext):
                errors.append(f"{k1} ({s}) shares text with {k2}: {sh!r}")
    return {"ok": not errors, "errors": errors, "summary": summary(sets)}


def summary(sets: Mapping[str, Sequence[Mapping[str, Any]]]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for s, convs in sets.items():
        out[s] = {
            "n_conversations": len(convs),
            "n_requests": sum(len(user_turns(c)) for c in convs),
            "n_multi_turn": sum(1 for c in convs if len(user_turns(c)) > 1),
            "generation_budget_tokens": sum(generation_budget(c) for c in convs),
            "lang": dict(sorted(collections.Counter(str(c.get("lang")) for c in convs).items())),
            "category": dict(sorted(collections.Counter(str(c.get("category")) for c in convs).items())),
            "input_chars": sum(len(t) for c in convs for t in _conv_texts(c)),
        }
    return out


