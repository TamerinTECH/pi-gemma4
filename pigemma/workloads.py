def _find(sets: Mapping[str, Sequence[Mapping[str, Any]]], cid: str) -> Mapping[str, Any]:
    for convs in sets.values():
        for c in convs:
            if c.get("id") == cid:
                return c
    raise KeyError(cid)


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m pigemma.workloads", description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    v = sub.add_parser("validate")
    v.add_argument("--dir", default=None)
    v.add_argument("--json", action="store_true")
    s = sub.add_parser("summary")
    s.add_argument("--dir", default=None)
    r = sub.add_parser("render")
    r.add_argument("id")
    r.add_argument("--turn", type=int, default=0)
    r.add_argument("--dir", default=None)
    c = sub.add_parser("count-tokens")
    c.add_argument("--dir", default=None)
    c.add_argument("--model", default="26b-q4")
    c.add_argument("--bin", default=None)
    c.add_argument("--out", default=str(WORKLOADS_DIR / "token_counts.json"))
    a = ap.parse_args(argv)
    if a.cmd == "validate":
        rep = validate_all(a.dir)
        if a.json:
            print(json.dumps(rep, ensure_ascii=False, indent=1))
        else:
            for e in rep["errors"]:
                print("ERROR", e)
            print(json.dumps(rep["summary"], ensure_ascii=False, indent=1))
            print("OK" if rep["ok"] else f"{len(rep['errors'])} error(s)")
        return 0 if rep["ok"] else 1
    sets = load_all(a.dir)
    if a.cmd == "summary":
        print(json.dumps(summary(sets), ensure_ascii=False, indent=1))
        return 0
    if a.cmd == "render":
        conv = _find(sets, a.id)
        try:
            sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[attr-defined]
        except (AttributeError, ValueError):
            pass
        print(render_gemma4(request_messages(conv, a.turn, [f"<REPLY {j}>" for j in range(a.turn)])))
        return 0
    if a.cmd == "count-tokens":
        model = paths.model_path(a.model)
        rep = token_report(sets, model, a.bin)
        Path(a.out).write_text(json.dumps(rep, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(json.dumps(rep["by_set"], indent=1))
        print(a.out)
        return 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
