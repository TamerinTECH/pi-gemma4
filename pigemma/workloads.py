# Requests and the Gemma 4 chat template
# --------------------------------------------------------------------------------------------
def request_messages(conv: Mapping[str, Any], k: int, replies: Sequence[str]) -> list[dict[str, str]]:
    """OpenAI-style messages of the k-th request (0-based) of a conversation.

    ``replies[j]`` is the model's (visible) reply to user turn j; the first k replies are needed.
    """
    turns = list(conv.get("turns") or [])
    n_user = len(user_turns(conv))
    if not 0 <= k < n_user:
        raise IndexError(f"{conv.get('id')}: request {k} of {n_user}")
    if len(replies) < k:
        raise ValueError(f"{conv.get('id')}: request {k} needs {k} earlier replies, got {len(replies)}")
    out: list[dict[str, str]] = []
    u = 0
    for t in turns:
        if t["role"] == "system":
            out.append({"role": "system", "content": t["content"]})
            continue
        out.append({"role": "user", "content": t["content"]})
        if u == k:
            break
        out.append({"role": "assistant", "content": str(replies[u])})
        u += 1
    return out


def _strip_thinking_template(text: str) -> str:
    """The template's strip_thinking macro: drop '<|channel>...' up to each '<channel|>', trim."""
    res = ""
    for part in str(text).split("<channel|>"):
        res += part.split("<|channel>")[0] if "<|channel>" in part else part
    return res.strip()


def render_gemma4(messages: Sequence[Mapping[str, Any]], *, add_generation_prompt: bool = True,
                  enable_thinking: bool = False, bos: bool = False) -> str:
    """Render plain-text system/user/assistant messages exactly like the Gemma 4 GGUF chat
    template (no tools, no media, no reasoning_content). ``bos=True`` prepends the literal
    ``<bos>`` the template emits; leave it False when the text is tokenised by a llama.cpp tool
    that adds BOS itself (llama-tokenize, llama-completion, the probe).

    Verified against the template stored in tests/fixtures/gemma4_chat_template.jinja (jinja2).
    Note: an earlier assistant reply is re-rendered WITHOUT the empty thought block that the
    generation prompt contained when it was produced, so the KV prefix of a follow-up request
    matches the cached tokens only up to that reply's ``<|turn>model\\n`` (see the README).
    """
    msgs = list(messages)
    out = [BOS_TEXT] if bos else []
    if enable_thinking or (msgs and msgs[0].get("role") in ("system", "developer")):
        out.append(TURN_OPEN + "system\n")
        if enable_thinking:
            out.append("<|think|>\n")
        if msgs and msgs[0].get("role") in ("system", "developer"):
            out.append(str(msgs[0].get("content", "")).strip())
            msgs = msgs[1:]
        out.append(TURN_CLOSE + "\n")
    prev_role = None
    for m in msgs:
        role = m.get("role")
        if role not in ("user", "assistant"):
            raise ValueError(f"render_gemma4 supports system/user/assistant only, got {role!r}")
        trole = "model" if role == "assistant" else "user"
        if trole == "model" and prev_role == "assistant":
            raise ValueError("render_gemma4: consecutive assistant messages are not supported "
                             "(the template merges them into one model turn)")
        out.append(TURN_OPEN + trole + "\n")
        content = str(m.get("content", ""))
        out.append(_strip_thinking_template(content) if trole == "model" else content.strip())
        out.append(TURN_CLOSE + "\n")
        prev_role = role
    if add_generation_prompt:
        out.append(TURN_OPEN + "model\n")
        if not enable_thinking:
            out.append(EMPTY_THOUGHT)
    return "".join(out)


def expected_reuse_note() -> str:
    return ("follow-up request k reuses at most the tokens of request k-1's prompt up to and "
            "including its final '<|turn>model\\n' (the empty thought block of the generation "
            "prompt and the reply are re-rendered differently: the reply without the thought "
            "block, trimmed); compare timings.cache_n with the token count of that prefix")


# --------------------------------------------------------------------------------------------
# Token counts (measured with llama-tokenize, vocab-only load)
# --------------------------------------------------------------------------------------------
def count_tokens(texts: Sequence[str], model: str | os.PathLike[str],
                 binary: str | os.PathLike[str] | None = None, *, timeout: float = 60.0) -> list[int]:
    """Token count of each text (BOS included, special tokens parsed, escapes NOT processed)
    with ``llama-tokenize -m MODEL -f FILE --ids --no-escape --log-disable``. llama-tokenize
    loads only the vocabulary (vocab_only=true at a7b94df): no weights, no inference."""
    exe = Path(binary) if binary else paths.bin("llama-tokenize")
    if not exe.is_file():
        raise FileNotFoundError(f"llama-tokenize not found: {exe}")
    counts: list[int] = []
    with tempfile.TemporaryDirectory(prefix="pigemma-tok-") as td:
        for i, t in enumerate(texts):
            f = Path(td) / f"t{i}.txt"
            f.write_bytes(str(t).encode("utf-8"))
            cp = subprocess.run([str(exe), "-m", os.fspath(model), "-f", str(f), "--ids",
                                 "--no-escape", "--log-disable"], capture_output=True,
                                timeout=timeout, check=False)
            outs = cp.stdout.decode("utf-8", errors="replace").strip().splitlines()
            ids_line = next((ln for ln in reversed(outs) if ln.startswith("[") and ln.endswith("]")), None)
            if cp.returncode != 0 or ids_line is None:
                raise RuntimeError(f"llama-tokenize failed (rc {cp.returncode}): "
                                   f"{cp.stderr.decode('utf-8', errors='replace')[-400:]}")
            body = ids_line[1:-1].strip()
            counts.append(len(body.split(",")) if body else 0)
    return counts


def token_report(sets: Mapping[str, Sequence[Mapping[str, Any]]], model: str | os.PathLike[str],
                 binary: str | os.PathLike[str] | None = None) -> dict[str, Any]:
    """Token counts of every request of every conversation.

    Measured (llama-tokenize): ``prompt_tokens_empty_replies[k]`` = the rendered prompt of
    request k with every earlier reply EMPTY (template tokens + all user turns, BOS included),
    and ``thought_block_tokens`` (the empty thought block of the generation prompt).
    Projected (upper bound, labelled): ``prompt_tokens_upper[k]`` = measured + k * max_tokens
    (every earlier reply at its full length); ``reusable_prefix_upper[k]`` = prompt_tokens_upper
    of request k-1 minus the thought block (the KV prefix llama-server can reuse, see
    expected_reuse_note); ``new_prefill_upper[k]`` = prompt minus reusable prefix
    (request 0 is sent with cache_prompt=false: everything is prefilled).
    """
    jobs: list[tuple[str, int, str]] = [("", -1, ""), ("", -2, EMPTY_THOUGHT)]
    for convs in sets.values():
        for c in convs:
            for k in range(len(user_turns(c))):
                jobs.append((str(c["id"]), k, render_gemma4(request_messages(c, k, [""] * k))))
    counts = count_tokens([j[2] for j in jobs], model, binary)
    bos_only, thought_plus_bos = counts[0], counts[1]
    thought = thought_plus_bos - bos_only
    per: dict[str, dict[str, Any]] = {}
    for (cid, _k, _t), n in zip(jobs[2:], counts[2:]):
        per.setdefault(cid, {"prompt_tokens_empty_replies": []})["prompt_tokens_empty_replies"].append(n)
    by_set: dict[str, dict[str, Any]] = {}
    for s, convs in sets.items():
        tot_prefill = 0
        tot_first = 0
        for c in convs:
            e = per[str(c["id"])]
            e["set"] = s
            mt = int(c["max_tokens"])
            meas = e["prompt_tokens_empty_replies"]
            upper = [m + k * mt for k, m in enumerate(meas)]
            reuse = [0] + [upper[k - 1] - thought for k in range(1, len(upper))]
            e["prompt_tokens_upper"] = upper
            e["reusable_prefix_upper"] = reuse
            e["new_prefill_upper"] = [u - r for u, r in zip(upper, reuse)]
            e["first_prompt_tokens"] = meas[0]
            e["length_class"] = ("long" if meas[0] >= 500 else "short" if meas[0] < 80 else "medium")
            tot_first += meas[0]
            tot_prefill += sum(e["new_prefill_upper"])
        by_set[s] = {
            "n_requests": sum(len(per[str(c["id"])]["prompt_tokens_empty_replies"]) for c in convs),
            "first_prompt_tokens_total": tot_first,
            "new_prefill_tokens_per_pass_upper": tot_prefill,
            "generation_budget_tokens": sum(generation_budget(c) for c in convs),
            "length_classes": dict(sorted(collections.Counter(
                per[str(c["id"])]["length_class"] for c in convs).items())),
        }
    exe = Path(binary) if binary else paths.bin("llama-tokenize")
    return {
        "format": "pigemma-workload-tokens/2",
        "kind": {"prompt_tokens_empty_replies": "measured", "thought_block_tokens": "measured",
                 "first_prompt_tokens": "measured",
                 "prompt_tokens_upper / reusable_prefix_upper / new_prefill_upper":
                     "projected upper bound (every earlier reply at max_tokens; reuse as in "
                     "expected_reuse_note) - not a measurement"},
        "tool": {"binary": paths.repo_relative(exe), "llama_commit": paths.LLAMA_COMMIT,
                 "flags": "-m MODEL -f FILE --ids --no-escape --log-disable (BOS added, specials parsed)",
                 "model": paths.repo_relative(model), "load": "vocab_only (no weights, no inference)"},
        "rendering": "pigemma.workloads.render_gemma4 (thinking disabled, bos=False; the tool adds BOS)",
        "bos_tokens": bos_only, "thought_block_tokens": thought,
        "length_class_rule": "short < 80 <= medium < 500 <= long (first-request prompt tokens)",
        "files_sha256": {s: hashlib.sha256(_set_path(s).read_bytes()).hexdigest()
                         for s in SETS if _set_path(s).is_file()},
        "by_set": by_set,
        "conversations": per,
    }


