"""pigemma.workloads - the request workloads of the decision milestone (data/workloads/*.jsonl).

Three DISJOINT sets (brief 2026-10-05, sections 3, 4 and 7):

* ``calibration.jsonl`` - used ONLY to rank experts (routing traces from real generations);
* ``tuning.jsonl``      - used ONLY for the pilot / pinning-budget choice;
* ``heldout.jsonl``     - used ONLY for the evaluation (A/B/C/D comparison).

One JSON object per line = one request or one multi-turn conversation::

    {"id": "ho-07", "set": "heldout", "lang": "en|he|de|mixed", "category": "<CATEGORIES>",
     "turns": [{"role": "system"|"user", "content": "..."}, ...],
     "max_tokens": 48..96, "context_reuse": "none" | "follow_up_same_conversation",
     "notes": "..."}

Semantics (also in data/workloads/README.md):

* ``turns`` holds the INPUT messages only (an optional leading ``system`` message, then one or
  more ``user`` messages). The assistant reply after every user message is GENERATED by the model
  under test (greedy) and appended to the history before the next user message is sent, so
  follow-up prompts contain real model output.
* ``max_tokens`` is the fixed generation length bound PER assistant reply (sent to llama-server
  as its native ``n_predict``); a conversation generates at most ``max_tokens * n_user_turns``.
* ``context_reuse == "none"``: single request, no KV prefix from an earlier request may be used
  (send ``cache_prompt: false``). ``"follow_up_same_conversation"``: the 2nd..nth requests are
  sent back-to-back on the same llama-server slot with ``cache_prompt: true``; the first request
  of the conversation is sent with ``cache_prompt: false``. The reuse that actually happened is
  read from ``timings.cache_n`` and compared with ``expected_reuse_note()`` - see the README for
  why Gemma 4's template limits the reusable prefix.

Python API::

    load_set(name_or_path) -> [conv]          validate_conversation(conv, expected_set) -> [error]
    load_all(dir) -> {set: [conv]}            validate_all(dir, *, check_external=True) -> report
    user_turns(conv) -> [str]                 generation_budget(conv) -> int
    request_messages(conv, k, replies) -> [message]   (history for the k-th request, 0-based)
    render_gemma4(messages, *, add_generation_prompt=True, enable_thinking=False, bos=False)
    shingles(text, n=8) -> set[str]           count_tokens(texts, model, binary=None) -> [int]

CLI (``python -m pigemma.workloads <cmd>``)::

    validate [--dir D] [--json]               exit 1 on any error (schema, disjointness, budget)
    summary  [--dir D]                        per-set counts, languages, categories, budgets
    render   ID [--turn K] [--dir D]          the rendered Gemma 4 prompt of request K (replies
                                              of earlier turns shown as <REPLY k> placeholders)
    count-tokens [--model 26b-q4] [--bin PATH] [--out data/workloads/token_counts.json]
                                              measured token counts with llama-tokenize
                                              (vocab-only load; no weights, no inference)

Stdlib only (runs on the Pi's Python 3.13).
"""

